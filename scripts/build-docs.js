#!/usr/bin/env node
/**
 * Builds the GitHub Pages site under docs/:
 *  - docs/data.js      the special-days dataset as an ES module (browser import)
 *  - docs/core.js      a copy of src/core.js (the page imports it directly)
 *  - docs/today.json   today's verdict (UTC), consumed by the shields.io badge
 *  - docs/badge.json   shields.io "endpoint" payload for the README badge
 *
 * Run daily by .github/workflows/daily.yml so the badge stays current.
 */
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { checkDate, formatLine } from '../src/core.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'data/special-days.json'), 'utf8'));

// 1. dataset as a module
writeFileSync(join(root, 'docs/data.js'), `// generated by scripts/build-docs.js — do not edit\nexport default ${JSON.stringify(data)};\n`);

// 2. core logic
copyFileSync(join(root, 'src/core.js'), join(root, 'docs/core.js'));

// 3. today's verdict in UTC (the Daily resets at midnight in the player's local time; UTC is the neutral choice for a shared badge)
const now = new Date();
const today = { month: now.getUTCMonth() + 1, day: now.getUTCDate(), year: now.getUTCFullYear() };
const result = checkDate(data, today);
writeFileSync(join(root, 'docs/today.json'), JSON.stringify({ generatedAt: now.toISOString(), ...result, line: formatLine(result) }, null, 2));

// 4. shields.io endpoint badge: https://shields.io/badges/endpoint-badge
const message = result.special ? result.reasons[0].label.toLowerCase() : 'regular';
writeFileSync(join(root, 'docs/badge.json'), JSON.stringify({
  schemaVersion: 1,
  label: `Wordscapes daily ${result.label}`,
  message,
  color: result.special ? 'ff6f61' : '4b5563',
  cacheSeconds: 3600,
}, null, 2));

console.log(formatLine(result));
